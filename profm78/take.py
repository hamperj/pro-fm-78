"""profm78/p5/ from Melodee's own tree (github.com/keremimo/melodee): its Prophet engine
(firmware/src/eng_prophet_test.c, as p5/eng_prophet.c), its native patch code and its maths, unchanged but
for their section names: what Melodee's linker puts in RAM (.dsp_text, .audio_text, .dsp_tables) is the
module's .ram_text / RAM .data, and its .pool is plain .bss (a module's RAM is one region, cleared by the
host). Melodee's own generators make the rest: the engine's tables (tools/gen_tables.py, only the parts the
engine reads) and Sequential's 200 factory programs (tools/gen_prophet_factory.py, from Sequential's
unchanged v1.03 SysEx, checked by its SHA-256). Run it again on a new Melodee:
    profm78/take.py ~/src/melodee        (Melodee 165d177, 1.6.1)"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

src = Path(sys.argv[1]).resolve()
fw = src / "firmware/src"
out = Path(__file__).resolve().parent / "p5"
(out / "x0x").mkdir(parents=True, exist_ok=True)
for f in ["prophet_patch.c", "performance_options.h", "x0x/fastmath.h"]:
    shutil.copy(fw / f, out / f)
shutil.copy(src / "LICENSE", out / "LICENSE")
shutil.copy(src / "LICENSING.md", out / "LICENSING.md")
shutil.copy(src / "assets/prophet5-factory/README.md", out / "FACTORY.md")


def sub(t, old, new, n):
    assert t.count(old) == n, (old, t.count(old))
    return t.replace(old, new)


e = (fw / "eng_prophet_test.c").read_text()
e = sub(e, ' __attribute__((section(".pool")))', "", 1)
e = sub(e, 'section(".dsp_text")', "section(P5_RAM_TEXT)", 4)       # (profm78_melodee.inc: .ram_text, or a Mac's)
e = sub(e, 'section(".audio_text")', "section(P5_RAM_TEXT)", 1)
(out / "eng_prophet.c").write_text(e)


def run(script, *args):
    # Melodee's generators: standard library only; -I so nothing of Melodee's tree is imported by accident
    subprocess.run([sys.executable, "-I", str(src / "tools" / script), *map(str, args)], check=True)


def cut(lines, first, last):
    """lines[first..last], first and last found by their start (each once)"""
    a = [i for i, s in enumerate(lines) if s.startswith(first)]
    assert len(a) == 1, (first, a)
    b = next(i for i in range(a[0], len(lines)) if lines[i].startswith(last))
    return lines[a[0]:b + 1]


with tempfile.TemporaryDirectory() as tmp:
    run("gen_tables.py", Path(tmp) / "t.h")
    t = (Path(tmp) / "t.h").read_text().split("\n")
    run("gen_prophet_factory.py", out / "melodee_prophet_factory.h")
p5 = cut(t, "#if !defined(MELODEE_PROPHET) || MELODEE_PROPHET", "static const uint16_t LEVEL_Q12")[:-1]
assert p5[-1] == "#endif", p5[-1]
tables = (["/* generated by profm78/take.py from Melodee's tools/gen_tables.py: what eng_prophet.c reads */",
           "#pragma once", "#include <stdint.h>", "#define FS 44100", "#define CTL 32"]
          + cut(t, "static const uint32_t PITCH_OCT[", "};")
          + cut(t, "static inline uint32_t pitch_inc(", "}")
          + cut(t, "static const uint32_t ENV_LIN[", "};") + p5)
s = "\n".join(tables) + "\n"
assert "#define FS 44100" in "\n".join(t) and "#define CTL 32" in "\n".join(t)
s = sub(s, 'section(".dsp_tables")', "section(P5_RAM_DATA)", 4)   # (per-sample lookups: RAM, as Melodee's)
(out / "p5_tables.h").write_text(s)
print("profm78: Melodee", src, "->", out)
